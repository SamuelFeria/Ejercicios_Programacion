lista=['elefante','perro','gato']
print (lista[0:len(lista)]) #Muestra toda la lista desde el principio hasta el fin.
print (lista [:])#Muestra toda el rango de elementos que le indiquemos entre los dos puntos.
print (lista [-1])#Muestra el ultimo elemento.
print (lista [-len(lista)])#Muestra el primer elemento usando indices negativos.
print (lista [-len (lista):])#Muestra toda la lista desde el primer elemento.
print (lista [:len(lista)])#Muestra toda la lista desde el principio hasta el final.
print (lista [len(lista)-1])#Muestra el ultimo elemento usando indices positivos.